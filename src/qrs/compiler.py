"""Compiles a strategy graph into a readable Python module that calls registered operators.

The output depends only on nodes, edges and normalised parameters, with nodes in a deterministic
dependency order. The same strategy therefore always compiles to byte-identical code, and the
code's SHA-256 identifies the executable strategy. Canvas layout and names never reach the code."""

from collections import defaultdict
from datetime import date
from pathlib import Path

from qrs import registry
from qrs.contracts import Issue, PortRef, StrategyDocument
from qrs.graph import check_data, topological_order, validate

HEADER = '''"""Generated by the qrs compiler from a qrs/strategy v1 document. Do not edit: change the
strategy and compile again. Run it with qrs.runtime.execute()."""

from qrs.runtime import Run
'''


class InvalidStrategy(ValueError):
    def __init__(self, issues: list[Issue]):
        self.issues = issues
        super().__init__("; ".join(f"{i.node}: {i.message}" if i.node else i.message for i in issues))


def compile_for_data(doc: StrategyDocument, data_dir: Path, until: date | None = None) -> str:
    """Compile a strategy and check it against its datasets, counting only sessions before `until` if
    it is given. The studio, the CLI and export all use this one gate, so they accept and refuse the
    same strategies."""
    code = compile_strategy(doc)
    issues = check_data(doc, data_dir, until)
    if issues:
        raise InvalidStrategy(issues)
    return code


def compile_strategy(doc: StrategyDocument) -> str:
    issues = validate(doc)
    if issues:
        raise InvalidStrategy(issues)
    nodes = {n.id: n for n in doc.nodes}
    ops = {n.id: registry.get(n.operator, n.version) for n in doc.nodes}
    wiring: dict[str, dict[str, PortRef]] = defaultdict(dict)
    for edge in doc.edges:
        wiring[edge.target.node][edge.target.port] = edge.source

    lines = [HEADER]
    for module in sorted({op.module for op in ops.values() if op.module.split(".")[0] != "qrs"}):
        lines.append(f"import {module}  # registers operators used below")
    lines += ["", "def run(ctx: Run) -> None:"]
    for node_id in topological_order(doc):
        node = nodes[node_id]
        params = ops[node_id].params.model_validate(node.params).model_dump(mode="json")
        inputs = ", ".join(f"{port!r}: {src.node}[{src.port!r}]" for port, src in sorted(wiring[node_id].items()))
        lines.append(f"    {node_id} = ctx.op({node_id!r}, {node.operator!r}, {node.version}, {{{inputs}}}, {params!r})")
    return "\n".join(lines) + "\n"
